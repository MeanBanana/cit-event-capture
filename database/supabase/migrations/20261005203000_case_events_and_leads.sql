-- Case history, lead investigators, case status rules and verified detections.
--
--   caseevent      one row for everything that happens to a submission or
--                  case (submitted, added/removed, rejected, status change,
--                  investigator assigned...). Triggers write it, so it's
--                  complete no matter which screen or function made the
--                  change. The app can't edit or delete it, it's the audit
--                  trail.
--   lead           caseassignment.islead, at most one active lead per case.
--                  The first investigator assigned becomes lead.
--   set_case_status  admins can set anything. Assigned investigators can
--                  only flip between open and under_review, closing and
--                  reopening is the admin's call.
--   verified       an investigator on the case (or an admin) confirms an AI
--                  detection, so we can tell AI guesses from confirmed facts


-- --- 1. caseevent
CREATE TABLE public.caseevent (
  eventid    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- SET NULL so deleting a case or incident doesn't wipe its history
  caseid     integer     REFERENCES public.cases (caseid) ON DELETE SET NULL,
  incidentid integer     REFERENCES public.crimescene (incidentid) ON DELETE SET NULL,
  actor      integer     REFERENCES public."User" (userid),   -- NULL means the system / AI pipeline
  eventtype  varchar(30) NOT NULL CHECK (eventtype IN (
               'submitted',
               'added_to_case',      -- also used when moved in from another case
               'removed_from_case',  -- also used when moved out to another case
               'rejected',
               'duplicate',
               'reopened',           -- back to pending review
               'case_created',
               'case_edited',        -- title or description
               'status_changed',
               'case_deleted',
               'assigned',
               'unassigned',
               'lead_changed',
               'detection_verified',
               'detection_unverified')),
  detail     text,                   -- e.g. 'open → under review'
  occurredat timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.caseevent ENABLE ROW LEVEL SECURITY;

-- a case's timeline, newest first, and its last activity
CREATE INDEX idx_caseevent_case     ON public.caseevent (caseid, occurredat DESC);
CREATE INDEX idx_caseevent_incident ON public.caseevent (incidentid, occurredat DESC);
CREATE INDEX idx_caseevent_actor    ON public.caseevent (actor);

-- read-only for the app, only the triggers below write rows
REVOKE ALL ON public.caseevent FROM anon;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, TRIGGER, REFERENCES
  ON public.caseevent FROM authenticated;

-- Admins see everything, investigators see their own cases' history.
-- Citizens get nothing here, their app shows review status straight from
-- crimescene.
CREATE POLICY "caseevent_select" ON public.caseevent
  FOR SELECT TO authenticated
  USING (
       (SELECT public.current_user_role()) = 'admin'
    OR (caseid IS NOT NULL AND public.is_assigned_to_case(caseid))
  );

-- Write one event. SECURITY DEFINER since the app can't insert into
-- caseevent itself. The actor is whoever's logged in (NULL for the service key).
CREATE OR REPLACE FUNCTION public.log_case_event(
  p_eventtype  text,
  p_caseid     integer,
  p_incidentid integer,
  p_detail     text DEFAULT NULL
)
  RETURNS void
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path = ''
AS $$
  INSERT INTO public.caseevent (caseid, incidentid, actor, eventtype, detail)
  VALUES (p_caseid, p_incidentid, public.current_user_id(), p_eventtype, p_detail)
$$;

-- e.g. 'CASE-0003', 'INC-0042'
CREATE OR REPLACE FUNCTION public.case_ref(p_caseid integer)
  RETURNS text LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$ SELECT 'CASE-' || lpad(p_caseid::text, 4, '0') $$;

CREATE OR REPLACE FUNCTION public.incident_ref(p_incidentid integer)
  RETURNS text LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$ SELECT 'INC-' || lpad(p_incidentid::text, 4, '0') $$;

-- 'under_review' -> 'under review'
CREATE OR REPLACE FUNCTION public.status_label(p_status text)
  RETURNS text LANGUAGE sql IMMUTABLE SET search_path = ''
AS $$ SELECT replace(p_status, '_', ' ') $$;


-- submissions (crimescene)
CREATE OR REPLACE FUNCTION public.log_crimescene_event()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.log_case_event('submitted', NEW.caseid, NEW.incidentid, NEW.location);
    RETURN NEW;
  END IF;

  -- moved between cases: one event for each side so both timelines make sense
  IF NEW.caseid IS DISTINCT FROM OLD.caseid THEN
    IF OLD.caseid IS NOT NULL THEN
      PERFORM public.log_case_event('removed_from_case', OLD.caseid, NEW.incidentid,
        CASE WHEN NEW.caseid IS NOT NULL THEN 'moved to ' || public.case_ref(NEW.caseid) END);
    END IF;
    IF NEW.caseid IS NOT NULL THEN
      PERFORM public.log_case_event('added_to_case', NEW.caseid, NEW.incidentid,
        CASE
          WHEN NEW.reviewstatus = 'duplicate'
            THEN 'as a duplicate of ' || public.incident_ref(NEW.duplicateof)
          WHEN OLD.caseid IS NOT NULL
            THEN 'moved from ' || public.case_ref(OLD.caseid)
        END);
    END IF;
  END IF;

  IF NEW.reviewstatus IS DISTINCT FROM OLD.reviewstatus
     OR NEW.duplicateof IS DISTINCT FROM OLD.duplicateof THEN
    CASE NEW.reviewstatus
      WHEN 'rejected' THEN
        PERFORM public.log_case_event('rejected', OLD.caseid, NEW.incidentid, NEW.reviewnote);
      WHEN 'duplicate' THEN
        PERFORM public.log_case_event('duplicate', NEW.caseid, NEW.incidentid,
          'of ' || public.incident_ref(NEW.duplicateof));
      WHEN 'pending' THEN
        PERFORM public.log_case_event('reopened', NULL, NEW.incidentid, NULL);
      ELSE
        NULL;   -- 'accepted' already got logged as added_to_case above
    END CASE;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER log_crimescene_event
  AFTER INSERT OR UPDATE OF caseid, reviewstatus, duplicateof ON public.crimescene
  FOR EACH ROW EXECUTE FUNCTION public.log_crimescene_event();


-- cases
CREATE OR REPLACE FUNCTION public.log_cases_event()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.log_case_event('case_created', NEW.caseid, NULL, NEW.title);
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    -- the case row is gone, so put the reference in the detail text instead
    PERFORM public.log_case_event('case_deleted', NULL, NULL,
      public.case_ref(OLD.caseid) || ': ' || OLD.title);
    RETURN OLD;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    PERFORM public.log_case_event('status_changed', NEW.caseid, NULL,
      public.status_label(OLD.status) || ' → ' || public.status_label(NEW.status));
  END IF;
  IF NEW.title IS DISTINCT FROM OLD.title
     OR NEW.description IS DISTINCT FROM OLD.description THEN
    PERFORM public.log_case_event('case_edited', NEW.caseid, NULL,
      CASE WHEN NEW.title IS DISTINCT FROM OLD.title
           THEN 'title: ' || NEW.title ELSE 'description changed' END);
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER log_cases_insert
  AFTER INSERT ON public.cases
  FOR EACH ROW EXECUTE FUNCTION public.log_cases_event();
CREATE TRIGGER log_cases_update
  AFTER UPDATE OF status, title, description ON public.cases
  FOR EACH ROW EXECUTE FUNCTION public.log_cases_event();
CREATE TRIGGER log_cases_delete
  AFTER DELETE ON public.cases
  FOR EACH ROW EXECUTE FUNCTION public.log_cases_event();


-- --- 2. lead investigator
ALTER TABLE public.caseassignment
  ADD COLUMN islead boolean NOT NULL DEFAULT false;

-- backfill: whoever has been on each case longest becomes lead
UPDATE public.caseassignment ca
   SET islead = true
  FROM (SELECT DISTINCT ON (caseid) assignmentid
          FROM public.caseassignment
         WHERE assignmentstatus = 'active'
         ORDER BY caseid, dateassigned, assignmentid) first_on_case
 WHERE ca.assignmentid = first_on_case.assignmentid;

-- one active lead per case at most (past leads stay marked, as history)
CREATE UNIQUE INDEX caseassignment_one_active_lead
  ON public.caseassignment (caseid)
  WHERE islead AND assignmentstatus = 'active';

-- Same signature as before. The first investigator on a case, or the first
-- one after the lead left, becomes the lead.
CREATE OR REPLACE FUNCTION public.assign_investigator(
  p_caseid integer,
  p_userid integer
)
  RETURNS integer
  LANGUAGE plpgsql
  SET search_path = ''
AS $$
DECLARE
  v_status text;
  v_id     integer;
BEGIN
  PERFORM public.require_admin();

  SELECT status INTO v_status FROM public.cases WHERE caseid = p_caseid;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'Case % not found', p_caseid;
  ELSIF v_status = 'closed' THEN
    RAISE EXCEPTION 'Case % is closed; reopen it before assigning investigators', p_caseid;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.investigator WHERE userid = p_userid) THEN
    RAISE EXCEPTION 'User % is not an investigator', p_userid;
  END IF;

  SELECT assignmentid INTO v_id FROM public.caseassignment
   WHERE caseid = p_caseid AND assignedto = p_userid AND assignmentstatus = 'active';
  IF v_id IS NOT NULL THEN
    RETURN v_id;
  END IF;

  INSERT INTO public.caseassignment (caseid, assignedto, assignedby, islead)
  VALUES (p_caseid, p_userid, public.current_user_id(),
          NOT EXISTS (SELECT 1 FROM public.caseassignment
                       WHERE caseid = p_caseid AND islead
                         AND assignmentstatus = 'active'))
  RETURNING assignmentid INTO v_id;
  RETURN v_id;
END;
$$;

-- Make an active assignment the lead. The old lead stays on the case as a
-- regular investigator.
CREATE OR REPLACE FUNCTION public.set_case_lead(p_assignmentid integer)
  RETURNS void
  LANGUAGE plpgsql
  SET search_path = ''
AS $$
DECLARE
  v_caseid integer;
BEGIN
  PERFORM public.require_admin();

  SELECT caseid INTO v_caseid FROM public.caseassignment
   WHERE assignmentid = p_assignmentid AND assignmentstatus = 'active';
  IF v_caseid IS NULL THEN
    RAISE EXCEPTION 'Assignment % not found or no longer active', p_assignmentid;
  END IF;

  UPDATE public.caseassignment SET islead = false
   WHERE caseid = v_caseid AND islead AND assignmentstatus = 'active'
     AND assignmentid <> p_assignmentid;
  UPDATE public.caseassignment SET islead = true
   WHERE assignmentid = p_assignmentid;
END;
$$;

CREATE OR REPLACE FUNCTION public.log_assignment_event()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = ''
AS $$
DECLARE
  v_name text;
BEGIN
  SELECT concat_ws(' ', i.rank, u.firstname, u.surname) INTO v_name
  FROM public."User" u
  LEFT JOIN public.investigator i ON i.userid = u.userid
  WHERE u.userid = NEW.assignedto;

  IF TG_OP = 'INSERT' THEN
    PERFORM public.log_case_event('assigned', NEW.caseid, NULL,
      v_name || CASE WHEN NEW.islead THEN ' (lead)' ELSE '' END);
    RETURN NEW;
  END IF;

  IF OLD.assignmentstatus = 'active' AND NEW.assignmentstatus <> 'active' THEN
    PERFORM public.log_case_event('unassigned', NEW.caseid, NULL, v_name);
  ELSIF NEW.islead AND NOT OLD.islead AND NEW.assignmentstatus = 'active' THEN
    PERFORM public.log_case_event('lead_changed', NEW.caseid, NULL, v_name || ' is now lead');
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER log_assignment_insert
  AFTER INSERT ON public.caseassignment
  FOR EACH ROW EXECUTE FUNCTION public.log_assignment_event();
CREATE TRIGGER log_assignment_update
  AFTER UPDATE OF assignmentstatus, islead ON public.caseassignment
  FOR EACH ROW EXECUTE FUNCTION public.log_assignment_event();

-- return type changed (added islead), so drop and recreate
DROP FUNCTION public.list_case_assignments(integer);
CREATE FUNCTION public.list_case_assignments(p_caseid integer)
  RETURNS TABLE (
    assignmentid     integer,
    userid           integer,
    name             text,
    badgenumber      varchar,
    station          varchar,
    dutystatus       varchar,
    assignmentstatus varchar,
    dateassigned     timestamptz,
    dateunassigned   timestamptz,
    assignedbyname   text,
    islead           boolean
  )
  LANGUAGE sql STABLE SECURITY INVOKER
  SET search_path = ''
AS $$
  SELECT ca.assignmentid, ca.assignedto,
         concat_ws(' ', i.rank, u.firstname, u.surname),
         i.badgenumber, i.station, i.dutystatus,
         ca.assignmentstatus, ca.dateassigned, ca.dateunassigned,
         NULLIF(trim(b.firstname || ' ' || b.surname), ''),
         ca.islead
  FROM public.caseassignment ca
  JOIN public."User" u ON u.userid = ca.assignedto
  LEFT JOIN public.investigator i ON i.userid = ca.assignedto
  LEFT JOIN public."User" b ON b.userid = ca.assignedby
  WHERE ca.caseid = p_caseid
  ORDER BY (ca.assignmentstatus = 'active') DESC,
           (ca.islead AND ca.assignmentstatus = 'active') DESC,
           ca.dateassigned DESC
$$;


-- --- 3. case status
-- SECURITY DEFINER because investigators can't update cases directly
-- (cases_update is admin-only), the checks in here decide instead.
CREATE OR REPLACE FUNCTION public.set_case_status(p_caseid integer, p_status text)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = ''
AS $$
DECLARE
  v_role text := public.current_user_role();
  v_old  text;
BEGIN
  IF p_status IS NULL OR p_status NOT IN ('open', 'under_review', 'closed') THEN
    RAISE EXCEPTION 'Unknown case status: %', p_status;
  END IF;

  SELECT status INTO v_old FROM public.cases WHERE caseid = p_caseid FOR UPDATE;
  IF v_old IS NULL THEN
    RAISE EXCEPTION 'Case % not found', p_caseid;
  END IF;

  IF v_role = 'admin' THEN
    NULL;                                  -- admins can set whatever they like
  ELSIF v_role = 'investigator' AND public.is_assigned_to_case(p_caseid) THEN
    IF v_old = 'closed' OR p_status = 'closed' THEN
      RAISE EXCEPTION 'Only an admin can close or reopen a case' USING ERRCODE = '42501';
    END IF;
  ELSE
    RAISE EXCEPTION 'You are not allowed to change this case' USING ERRCODE = '42501';
  END IF;

  IF v_old <> p_status THEN
    UPDATE public.cases SET status = p_status WHERE caseid = p_caseid;
  END IF;
END;
$$;


-- --- 4. verified detections
ALTER TABLE public.detection
  ADD COLUMN verified   boolean     NOT NULL DEFAULT false,
  ADD COLUMN verifiedby integer     REFERENCES public."User" (userid),
  ADD COLUMN verifiedat timestamptz,
  ADD CONSTRAINT detection_verified_check
    CHECK (verified = (verifiedby IS NOT NULL AND verifiedat IS NOT NULL));

CREATE INDEX idx_detection_verifiedby ON public.detection (verifiedby);

-- Admins and investigators on the case can confirm (or un-confirm) an AI
-- detection. detection has no UPDATE policy, so this is the only way to do it.
CREATE OR REPLACE FUNCTION public.verify_detection(
  p_detectionid integer,
  p_verified    boolean DEFAULT true
)
  RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = ''
AS $$
BEGIN
  IF public.current_user_role() NOT IN ('admin', 'investigator')
     OR NOT public.can_view_detection(p_detectionid) THEN
    RAISE EXCEPTION 'You are not allowed to verify this detection' USING ERRCODE = '42501';
  END IF;

  UPDATE public.detection
     SET verified   = p_verified,
         verifiedby = CASE WHEN p_verified THEN public.current_user_id() END,
         verifiedat = CASE WHEN p_verified THEN now() END
   WHERE detectionid = p_detectionid
     AND verified IS DISTINCT FROM p_verified;
END;
$$;

CREATE OR REPLACE FUNCTION public.log_detection_event()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path = ''
AS $$
DECLARE
  v_incidentid integer;
  v_caseid     integer;
BEGIN
  SELECT m.incidentid, cs.caseid INTO v_incidentid, v_caseid
  FROM public.media m
  JOIN public.crimescene cs ON cs.incidentid = m.incidentid
  WHERE m.mediaid = NEW.mediaid;

  PERFORM public.log_case_event(
    CASE WHEN NEW.verified THEN 'detection_verified' ELSE 'detection_unverified' END,
    v_caseid, v_incidentid,
    NEW.detectiontype || ' detection D-' || lpad(NEW.detectionid::text, 3, '0'));
  RETURN NEW;
END;
$$;

CREATE TRIGGER log_detection_event
  AFTER UPDATE OF verified ON public.detection
  FOR EACH ROW
  WHEN (NEW.verified IS DISTINCT FROM OLD.verified)
  EXECUTE FUNCTION public.log_detection_event();


-- --- 5. case history for the app
-- Newest first, 30 at a time. Pass the last eventid you have as p_before for
-- the next page.
CREATE OR REPLACE FUNCTION public.list_case_events(
  p_caseid integer,
  p_limit  integer DEFAULT 30,
  p_before bigint  DEFAULT NULL
)
  RETURNS TABLE (
    eventid    bigint,
    eventtype  varchar,
    incidentid integer,
    detail     text,
    actorname  text,          -- NULL for the system or if you can't see who it was
    occurredat timestamptz
  )
  LANGUAGE sql STABLE SECURITY INVOKER
  SET search_path = ''
AS $$
  SELECT e.eventid, e.eventtype, e.incidentid, e.detail,
         NULLIF(trim(u.firstname || ' ' || u.surname), ''),
         e.occurredat
  FROM public.caseevent e
  LEFT JOIN public."User" u ON u.userid = e.actor
  WHERE e.caseid = p_caseid
    AND (p_before IS NULL OR e.eventid < p_before)
  ORDER BY e.eventid DESC
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 30), 1), 100)
$$;



-- =====================================================================
-- Argus Shield: a proper "cases" table
--
-- Before: a case was just a crimescene row, and caseassignment pointed
--         straight at crimescene.incidentid.
-- After:  cases           one investigation, created by an admin
--         crimescene      each reported incident; caseid links it to a case
--                         (NULL = not yet added to a case)
--         caseassignment  investigator <-> CASE (no longer per incident)
--
--   cases 1 ──< crimescene 1 ──< media / suspect
--   cases 1 ──< caseassignment >── 1 "User" (investigator)
--
-- An investigator assigned to a case can see every incident in it, plus the
-- media, detections and suspects of those incidents. is_assigned_to(incidentid)
-- keeps its name and arguments, so none of the existing policies change.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. The cases table
-- ---------------------------------------------------------------------
CREATE TABLE public.cases (
  caseid      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       varchar(150)             NOT NULL,     -- e.g. 'N1 Midrand CIT robbery'
  description text,
  status      varchar(50)              NOT NULL DEFAULT 'open'
              CHECK (status IN ('open', 'under_review', 'closed')),
  createdby   integer                  NOT NULL REFERENCES public."User" (userid),
  datecreated timestamptz              NOT NULL DEFAULT now(),
  dateclosed  timestamptz                         -- filled in automatically, see below
);

ALTER TABLE public.cases ENABLE ROW LEVEL SECURITY;

CREATE INDEX idx_cases_createdby   ON public.cases (createdby);
CREATE INDEX idx_cases_datecreated ON public.cases (datecreated DESC);  -- "most recent cases"

-- dateclosed is set when a case is closed and cleared if it is reopened,
-- so the app only ever has to change status
CREATE OR REPLACE FUNCTION public.set_case_dateclosed()
  RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
AS $$
BEGIN
  IF NEW.status = 'closed' THEN
    NEW.dateclosed := COALESCE(NEW.dateclosed, now());
  ELSE
    NEW.dateclosed := NULL;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER set_case_dateclosed
  BEFORE INSERT OR UPDATE OF status, dateclosed ON public.cases
  FOR EACH ROW EXECUTE FUNCTION public.set_case_dateclosed();


-- ---------------------------------------------------------------------
-- 2. Incidents belong to a case
--    ON DELETE SET NULL: deleting a case does not delete the evidence,
--    the incidents just go back to "not in a case".
-- ---------------------------------------------------------------------
ALTER TABLE public.crimescene
  ADD COLUMN caseid integer REFERENCES public.cases (caseid) ON DELETE SET NULL;

CREATE INDEX idx_crimescene_caseid ON public.crimescene (caseid);


-- ---------------------------------------------------------------------
-- 3. Assignments point at cases instead of incidents
-- ---------------------------------------------------------------------
ALTER TABLE public.caseassignment ADD COLUMN caseid integer;

-- Move any existing data across: every incident that already has an
-- assignment becomes its own case (title = location), created by whoever
-- made the first assignment.
DO $$
DECLARE
  r        record;
  v_caseid integer;
BEGIN
  FOR r IN
    SELECT DISTINCT ON (ca.incidentid)
           ca.incidentid, ca.assignedby, ca.dateassigned, cs.location, cs.status
    FROM public.caseassignment ca
    JOIN public.crimescene cs ON cs.incidentid = ca.incidentid
    ORDER BY ca.incidentid, ca.dateassigned
  LOOP
    INSERT INTO public.cases (title, status, createdby, datecreated)
    VALUES (left(r.location, 150), r.status, r.assignedby, r.dateassigned)
    RETURNING caseid INTO v_caseid;

    UPDATE public.crimescene     SET caseid = v_caseid WHERE incidentid = r.incidentid;
    UPDATE public.caseassignment SET caseid = v_caseid WHERE incidentid = r.incidentid;
  END LOOP;
END;
$$;

ALTER TABLE public.caseassignment
  ALTER COLUMN caseid SET NOT NULL,
  ADD CONSTRAINT caseassignment_caseid_fkey
    FOREIGN KEY (caseid) REFERENCES public.cases (caseid) ON DELETE CASCADE;

-- also drops caseassignment_incidentid_fkey and idx_caseassignment_incidentid
ALTER TABLE public.caseassignment DROP COLUMN incidentid;

CREATE INDEX idx_caseassignment_caseid ON public.caseassignment (caseid);

-- An investigator can only have one ACTIVE assignment on the same case
CREATE UNIQUE INDEX caseassignment_one_active_per_case
  ON public.caseassignment (caseid, assignedto)
  WHERE assignmentstatus = 'active';


-- ---------------------------------------------------------------------
-- 4. Helper functions
-- ---------------------------------------------------------------------
-- True when the signed-in investigator has an ACTIVE assignment on the case
CREATE OR REPLACE FUNCTION public.is_assigned_to_case(p_caseid integer)
  RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER
  SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.caseassignment ca
    WHERE ca.caseid = p_caseid
      AND ca.assignedto = public.current_user_id()
      AND ca.assignmentstatus = 'active'
  )
$$;

-- Same name and arguments as before, so the crimescene / media / suspect /
-- detection policies keep working: an incident is visible to an
-- investigator when they are assigned to the case it belongs to.
CREATE OR REPLACE FUNCTION public.is_assigned_to(p_incidentid integer)
  RETURNS boolean
  LANGUAGE sql STABLE SECURITY DEFINER
  SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.crimescene cs
    WHERE cs.incidentid = p_incidentid
      AND public.is_assigned_to_case(cs.caseid)
  )
$$;

REVOKE EXECUTE ON FUNCTION public.is_assigned_to_case(integer) FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION public.is_assigned_to_case(integer) TO authenticated, service_role;


-- ---------------------------------------------------------------------
-- 5. Only admins decide which case an incident belongs to
--    (citizens report incidents and investigators may update them, but
--    neither may move an incident into or out of a case)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.protect_crimescene_caseid()
  RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
AS $$
BEGIN
  IF current_user IN ('authenticated', 'anon')
     AND public.current_user_role() IS DISTINCT FROM 'admin'
     AND (   (TG_OP = 'INSERT' AND NEW.caseid IS NOT NULL)
          OR (TG_OP = 'UPDATE' AND NEW.caseid IS DISTINCT FROM OLD.caseid))
  THEN
    RAISE EXCEPTION 'Only admins can add an incident to a case';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER protect_crimescene_caseid
  BEFORE INSERT OR UPDATE ON public.crimescene
  FOR EACH ROW EXECUTE FUNCTION public.protect_crimescene_caseid();


-- ---------------------------------------------------------------------
-- 6. Privileges (same rules as the other tables: nothing for anon,
--    no TRUNCATE/TRIGGER/REFERENCES for logged-in users)
-- ---------------------------------------------------------------------
REVOKE ALL ON public.cases FROM anon;
REVOKE TRUNCATE, TRIGGER, REFERENCES ON public.cases FROM authenticated;


-- ---------------------------------------------------------------------
-- 7. Policies on cases
--    Admins: everything. Investigators: read the cases they are assigned
--    to. Citizens: nothing (they see their own incidents via crimescene).
-- ---------------------------------------------------------------------
CREATE POLICY "cases_select" ON public.cases
  FOR SELECT TO authenticated
  USING (
       (SELECT public.current_user_role()) = 'admin'
    OR public.is_assigned_to_case(caseid)
  );

CREATE POLICY "cases_insert" ON public.cases
  FOR INSERT TO authenticated
  WITH CHECK (
    (SELECT public.current_user_role()) = 'admin'
    AND createdby = (SELECT public.current_user_id())
  );

CREATE POLICY "cases_update" ON public.cases
  FOR UPDATE TO authenticated
  USING      ((SELECT public.current_user_role()) = 'admin')
  WITH CHECK ((SELECT public.current_user_role()) = 'admin');

CREATE POLICY "cases_delete" ON public.cases
  FOR DELETE TO authenticated
  USING ((SELECT public.current_user_role()) = 'admin');

-- (caseassignment policies don't mention incidentid, so they stay as they are)

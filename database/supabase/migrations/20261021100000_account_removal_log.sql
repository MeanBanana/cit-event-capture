-- Removed accounts show up in the activity log, and the root admin can
-- remove station admins.
--
-- accountevent gets a row for every removed account: their name as it was
-- before we deleted/anonymised them, who removed them and when. Once an
-- account is gone there's nothing else recent_activity could build that
-- line from, so we write it down here. Neither app can edit or delete these.
--
-- remove_investigator_account works like before (20261020130000) but now
-- also logs an 'investigator_removed' line. manage-investigator calls it.
--
-- remove_admin_account lets root remove a station admin (never root itself).
-- Same idea as investigators: if they never did anything we delete the rows
-- and the function deletes the login ('deleted'). Otherwise their work stays
-- on record as "Former admin", the login gets blocked and the real email
-- freed up ('anonymised'). Logs an 'admin_removed' line. manage-admin calls
-- it from the web console.
--
-- recent_activity shows both as DEL lines, e.g.
--   'Investigator removed: Sgt Thabo Mokoena (B1234) by Kim Pillay'
--   'Admin removed: Sipho Dlamini (Sandton SAPS) by Deacon Nel'
--
-- Only the Edge Functions call the remove_* functions, with the service key,
-- after checking the caller themselves. removed_by is the caller's userid
-- because the service key has no user of its own.

-- --- 1. accountevent
CREATE TABLE public.accountevent (
  eventid    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  eventtype  varchar(30) NOT NULL CHECK (eventtype IN (
               'investigator_removed',
               'admin_removed')),
  detail     text        NOT NULL,   -- who got removed, e.g. 'Sgt Thabo Mokoena (B1234)'
  -- SET NULL so removing the admin who did it doesn't lose the line (actorname stays)
  actor      integer     REFERENCES public."User" (userid) ON DELETE SET NULL,
  actorname  text,
  occurredat timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_accountevent_time ON public.accountevent (occurredat DESC);

ALTER TABLE public.accountevent ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.accountevent FROM anon;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, TRIGGER, REFERENCES
  ON public.accountevent FROM authenticated;
GRANT SELECT ON public.accountevent TO authenticated;
GRANT ALL ON public.accountevent TO service_role;

-- admins only, it's for the Overview activity log
CREATE POLICY "accountevent_select" ON public.accountevent
  FOR SELECT TO authenticated
  USING ((SELECT public.current_user_role()) = 'admin');

-- write one line, keeping the actor's name as it is right now
CREATE OR REPLACE FUNCTION public.log_account_event(
  p_eventtype text,
  p_detail    text,
  p_actor     integer
)
  RETURNS void
  LANGUAGE sql
  SECURITY DEFINER
  SET search_path = ''
AS $$
  INSERT INTO public.accountevent (eventtype, detail, actor, actorname)
  VALUES (p_eventtype, p_detail, p_actor,
          (SELECT NULLIF(btrim(concat_ws(' ', u.firstname, u.surname)), '')
             FROM public."User" u WHERE u.userid = p_actor))
$$;


-- --- 2. remove_investigator_account, now with removed_by and a log line
DROP FUNCTION public.remove_investigator_account(integer);

CREATE OR REPLACE FUNCTION public.remove_investigator_account(
  p_userid     integer,
  p_removed_by integer DEFAULT NULL
)
  RETURNS jsonb
  LANGUAGE plpgsql
  VOLATILE SECURITY DEFINER
  SET search_path = ''
AS $$
DECLARE
  v_user    public."User";
  v_inv     public.investigator;
  v_name    text;
  v_case    integer;
  v_history boolean;
BEGIN
  SELECT * INTO v_user FROM public."User" WHERE userid = p_userid FOR UPDATE;
  SELECT * INTO v_inv FROM public.investigator WHERE userid = p_userid;
  IF v_user.userid IS NULL OR v_user.role <> 'investigator' OR v_inv.userid IS NULL THEN
    RAISE EXCEPTION 'That investigator account no longer exists.' USING ERRCODE = 'P0002';
  END IF;
  v_name := trim(v_user.firstname || ' ' || v_user.surname);

  -- grab this for the log before the details disappear
  PERFORM public.log_account_event(
    'investigator_removed',
    concat_ws(' ', v_inv.rank, v_user.firstname, v_user.surname) || ' (' || v_inv.badgenumber || ')',
    p_removed_by);

  -- end their active assignments, with a history line on each case
  FOR v_case IN
    UPDATE public.caseassignment
       SET assignmentstatus = 'closed', dateunassigned = now(), islead = false
     WHERE assignedto = p_userid AND assignmentstatus = 'active'
    RETURNING caseid
  LOOP
    PERFORM public.log_case_event('unassigned', v_case, NULL,
                                  v_name || ' (account deleted)');
  END LOOP;

  v_history :=
       EXISTS (SELECT 1 FROM public.caseassignment     WHERE assignedto = p_userid OR assignedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.casemessage        WHERE senderid = p_userid)
    OR EXISTS (SELECT 1 FROM public.caseevent          WHERE actor = p_userid)
    OR EXISTS (SELECT 1 FROM public.correctionlog      WHERE correctedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.crossreferencelink WHERE linkedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.detection          WHERE verifiedby = p_userid OR suspectreviewedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.suspect            WHERE confirmedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.entitymatchrejection WHERE rejectedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.crimescene         WHERE reportedby = p_userid OR reviewedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.media              WHERE uploadedby = p_userid)
    OR EXISTS (SELECT 1 FROM public.cases              WHERE createdby = p_userid);

  IF NOT v_history THEN
    DELETE FROM public."User" WHERE userid = p_userid;     -- investigator row goes with it
    RETURN jsonb_build_object('mode', 'deleted', 'authid', v_user.authid, 'name', v_name);
  END IF;

  DELETE FROM public.investigator WHERE userid = p_userid;
  UPDATE public."User"
     SET firstname   = 'Former',
         surname     = 'investigator',
         username    = 'deleted_' || p_userid,
         email       = 'deleted-' || p_userid || '@argus-shield.invalid',
         phonenumber = NULL
   WHERE userid = p_userid;
  RETURN jsonb_build_object('mode', 'anonymised', 'authid', v_user.authid, 'name', v_name,
                            'email', 'deleted-' || p_userid || '@argus-shield.invalid');
END;
$$;


-- --- 3. remove_admin_account (root only)
CREATE OR REPLACE FUNCTION public.remove_admin_account(
  p_userid     integer,
  p_removed_by integer
)
  RETURNS jsonb
  LANGUAGE plpgsql
  VOLATILE SECURITY DEFINER
  SET search_path = ''
AS $$
DECLARE
  v_user  public."User";
  v_admin public.admin;
  v_name  text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.admin
                  WHERE userid = p_removed_by AND admin_type = 'root') THEN
    RAISE EXCEPTION 'Only the root administrator can remove admin accounts.'
      USING ERRCODE = '42501';
  END IF;

  SELECT * INTO v_user FROM public."User" WHERE userid = p_userid FOR UPDATE;
  SELECT * INTO v_admin FROM public.admin WHERE userid = p_userid;
  IF v_user.userid IS NULL OR v_user.role <> 'admin' OR v_admin.userid IS NULL THEN
    RAISE EXCEPTION 'That admin account no longer exists.' USING ERRCODE = 'P0002';
  END IF;
  IF v_admin.admin_type = 'root' THEN
    RAISE EXCEPTION 'The root administrator can''t be removed.' USING ERRCODE = '42501';
  END IF;
  v_name := trim(v_user.firstname || ' ' || v_user.surname);

  PERFORM public.log_account_event(
    'admin_removed', v_name || ' (' || v_admin.admin_station || ')', p_removed_by);

  -- Admins touch a lot of tables (reviews, cases, assignments, corrections).
  -- Just try the delete, and if anything still points at them, keep the
  -- "User" row so their work stays on record, and anonymise it instead.
  BEGIN
    DELETE FROM public."User" WHERE userid = p_userid;     -- admin row goes with it
    RETURN jsonb_build_object('mode', 'deleted', 'authid', v_user.authid, 'name', v_name);
  EXCEPTION WHEN foreign_key_violation THEN
    NULL;                                                  -- has history, so anonymise below
  END;

  DELETE FROM public.admin WHERE userid = p_userid;
  UPDATE public."User"
     SET firstname   = 'Former',
         surname     = 'admin',
         username    = 'deleted_' || p_userid,
         email       = 'deleted-' || p_userid || '@argus-shield.invalid',
         phonenumber = NULL
   WHERE userid = p_userid;
  RETURN jsonb_build_object('mode', 'anonymised', 'authid', v_user.authid, 'name', v_name,
                            'email', 'deleted-' || p_userid || '@argus-shield.invalid');
END;
$$;


-- --- 4. recent_activity gets DEL lines for removed accounts
-- (body copied from 20261006081759_remote_schema.sql with one more UNION at the end)
CREATE OR REPLACE FUNCTION public.recent_activity(p_limit integer DEFAULT 5)
  RETURNS TABLE (
    tag        text,
    message    text,
    occurredat timestamptz
  )
  LANGUAGE sql STABLE SECURITY INVOKER
  SET search_path = ''
AS $$
  WITH events AS (
    SELECT 'NEW' AS tag,
           'New citizen submission: INC-' || lpad(cs.incidentid::text, 4, '0')
             || ', ' || cs.location AS message,
           cs.datereported AS occurredat
    FROM public.crimescene cs

    UNION ALL   -- admin decisions on submissions
    SELECT CASE cs.reviewstatus WHEN 'accepted' THEN 'ADD'
                                WHEN 'rejected' THEN 'REJ'
                                ELSE 'DUP' END,
           'INC-' || lpad(cs.incidentid::text, 4, '0') ||
           CASE cs.reviewstatus
             WHEN 'accepted' THEN ' added to CASE-' || lpad(cs.caseid::text, 4, '0')
             WHEN 'rejected' THEN ' rejected'
             ELSE ' marked as duplicate of INC-' || lpad(cs.duplicateof::text, 4, '0')
           END,
           cs.reviewedat
    FROM public.crimescene cs
    WHERE cs.reviewedat IS NOT NULL

    UNION ALL
    SELECT 'CASE',
           'Case CASE-' || lpad(c.caseid::text, 4, '0') || ' created: ' || c.title,
           c.datecreated
    FROM public.cases c

    UNION ALL
    SELECT 'ASGN',
           concat_ws(' ', i.rank, u.firstname, u.surname)
             || ' assigned to CASE-' || lpad(ca.caseid::text, 4, '0'),
           ca.dateassigned
    FROM public.caseassignment ca
    JOIN public."User" u ON u.userid = ca.assignedto
    LEFT JOIN public.investigator i ON i.userid = ca.assignedto

    UNION ALL
    SELECT 'CLSD',
           'CASE-' || lpad(c.caseid::text, 4, '0') || ' closed: ' || c.title,
           c.dateclosed
    FROM public.cases c
    WHERE c.dateclosed IS NOT NULL

    UNION ALL
    SELECT 'INV',
           'Investigator added: ' || concat_ws(' ', i.rank, u.firstname, u.surname)
             || ' (' || i.badgenumber || ')',
           u.datecreated
    FROM public.investigator i
    JOIN public."User" u ON u.userid = i.userid

    UNION ALL
    SELECT 'VER',
           'Suspect confirmed on INC-' || lpad(s.incidentid::text, 4, '0'),
           s.dateconfirmed
    FROM public.suspect s
    WHERE s.dateconfirmed IS NOT NULL

    UNION ALL
    SELECT 'COR',
           'Detection D-' || lpad(cl.detectionid::text, 3, '0') || ' corrected by '
             || COALESCE(u.firstname || ' ' || u.surname, 'a user'),
           cl.correctiontimestamp
    FROM public.correctionlog cl
    LEFT JOIN public."User" u ON u.userid = cl.correctedby

    UNION ALL   -- removed investigator/admin accounts
    SELECT 'DEL',
           CASE ae.eventtype WHEN 'investigator_removed' THEN 'Investigator removed: '
                             ELSE 'Admin removed: ' END
             || ae.detail || COALESCE(' by ' || ae.actorname, ''),
           ae.occurredat
    FROM public.accountevent ae
  )
  SELECT tag, message, occurredat
  FROM events
  ORDER BY occurredat DESC
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 5), 1), 50)   -- clamp to 1-50 rows
$$;



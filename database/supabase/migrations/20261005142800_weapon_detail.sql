-- weapondetail.
--
-- detection already allowed 'weapon', but only vehicles (vehicledetail) and
-- people (suspect) had anywhere to put details. This works exactly like
-- vehicledetail: one row per weapon detection, the pipeline writes it,
-- admins and investigators on the case can read it, and those investigators
-- can correct it.
--
--   detection 1 -- 0..1 weapondetail >-- 0..1 suspect (who was holding it)


-- --- 1. table
CREATE TABLE public.weapondetail (
  weapondetailid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  detectionid    integer     NOT NULL UNIQUE REFERENCES public.detection (detectionid),
  weapontype     varchar(50) NOT NULL DEFAULT 'unknown'
                 CHECK (weapontype IN ('handgun', 'rifle', 'shotgun', 'knife',
                                       'explosive', 'other', 'unknown')),
  -- who was carrying it, if we know. SET NULL so removing a suspect doesn't
  -- throw away the weapon evidence.
  suspectid      integer     REFERENCES public.suspect (suspectid) ON DELETE SET NULL,
  description    text                                  -- e.g. 'black pistol, right hand'
);

ALTER TABLE public.weapondetail ENABLE ROW LEVEL SECURITY;

CREATE INDEX idx_weapondetail_suspectid ON public.weapondetail (suspectid);


-- --- 2. consistency: it has to be a weapon detection, and a linked suspect
-- has to be from the same incident as the footage
CREATE OR REPLACE FUNCTION public.check_weapondetail()
  RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = ''
AS $$
DECLARE
  v_type       text;
  v_incidentid integer;
BEGIN
  SELECT d.detectiontype, m.incidentid
    INTO v_type, v_incidentid
  FROM public.detection d
  JOIN public.media m ON m.mediaid = d.mediaid
  WHERE d.detectionid = NEW.detectionid;

  IF v_type IS DISTINCT FROM 'weapon' THEN
    RAISE EXCEPTION 'weapondetail needs a detection of type weapon (detection % is %)',
      NEW.detectionid, COALESCE(v_type, 'missing');
  END IF;

  IF NEW.suspectid IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM public.suspect s
       WHERE s.suspectid = NEW.suspectid AND s.incidentid = v_incidentid)
  THEN
    RAISE EXCEPTION 'Suspect % is not part of the same incident as this weapon', NEW.suspectid;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER check_weapondetail
  BEFORE INSERT OR UPDATE ON public.weapondetail
  FOR EACH ROW EXECUTE FUNCTION public.check_weapondetail();


-- --- 3. privileges, same as the other tables
REVOKE ALL ON public.weapondetail FROM anon;
REVOKE TRUNCATE, TRIGGER, REFERENCES ON public.weapondetail FROM authenticated;


-- --- 4. policies, same as vehicledetail. The pipeline creates rows with the
-- service key, which skips RLS anyway.
CREATE POLICY "weapondetail_select" ON public.weapondetail
  FOR SELECT TO authenticated
  USING (public.can_view_detection(detectionid));

-- investigators on the case (and admins) can correct the type, description
-- or linked suspect
CREATE POLICY "weapondetail_update" ON public.weapondetail
  FOR UPDATE TO authenticated
  USING      (public.can_view_detection(detectionid))
  WITH CHECK (public.can_view_detection(detectionid));

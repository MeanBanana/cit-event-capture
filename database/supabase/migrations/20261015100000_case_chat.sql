-- Case chat: basically a WhatsApp group per case for the investigators on it.
-- The investigator case page has a Chat tab that shows messages live via
-- Realtime.
--
--   casemessage    caseid, senderid, body, sentat
--
-- Rules:
--   - investigators actively assigned to the case can read and send. Get
--     unassigned and the chat disappears for you straight away.
--   - admins can read any case's chat (oversight) but can't post
--   - nobody else sees anything
--   - closed cases are read-only
--   - messages can't be edited or deleted, they're part of the case record
--
-- From the app:
--   list_case_messages(caseid, after_id, limit)  messages with sender names
--   send_case_message(caseid, body)              returns the new message
--   Realtime: postgres_changes INSERT on casemessage, filter caseid=eq.<id>.
--   Realtime applies the SELECT policy, so only the right people get events.

CREATE TABLE public.casemessage (
  messageid  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caseid     integer     NOT NULL REFERENCES public.cases (caseid) ON DELETE CASCADE,
  senderid   integer     NOT NULL DEFAULT public.current_user_id()
                         REFERENCES public."User" (userid),
  body       text        NOT NULL
                         CHECK (length(btrim(body)) BETWEEN 1 AND 2000),
  sentat     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_casemessage_case   ON public.casemessage (caseid, messageid);
CREATE INDEX idx_casemessage_sender ON public.casemessage (senderid);

ALTER TABLE public.casemessage ENABLE ROW LEVEL SECURITY;

CREATE POLICY "casemessage_select" ON public.casemessage
  FOR SELECT TO authenticated
  USING (public.is_assigned_to_case(caseid)
         OR (SELECT public.current_user_role()) = 'admin');

CREATE POLICY "casemessage_insert" ON public.casemessage
  FOR INSERT TO authenticated
  WITH CHECK (
    senderid = (SELECT public.current_user_id())
    AND (SELECT public.current_user_role()) = 'investigator'
    AND public.is_assigned_to_case(caseid)
    AND EXISTS (SELECT 1 FROM public.cases c
                 WHERE c.caseid = casemessage.caseid AND c.status <> 'closed')
  );

-- deliberately no UPDATE/DELETE policies
REVOKE UPDATE, DELETE, TRUNCATE, TRIGGER, REFERENCES ON public.casemessage FROM authenticated, anon;
REVOKE ALL ON public.casemessage FROM anon;
GRANT SELECT, INSERT ON public.casemessage TO authenticated;
GRANT ALL ON public.casemessage TO service_role;


-- --- list_case_messages: the chat with sender names, oldest first
-- (investigators can't read each other's "User" rows, so we join them here)
--   p_after_id  only messages newer than this, for live updates
--   p_limit     the newest N, default 200
CREATE OR REPLACE FUNCTION public.list_case_messages(
  p_caseid   integer,
  p_after_id bigint  DEFAULT NULL,
  p_limit    integer DEFAULT 200
)
  RETURNS TABLE (
    messageid   bigint,
    caseid      integer,
    senderid    integer,
    sender_name text,
    is_mine     boolean,
    body        text,
    sentat      timestamptz
  )
  LANGUAGE plpgsql STABLE SECURITY DEFINER
  SET search_path = ''
AS $$
BEGIN
  IF NOT public.is_assigned_to_case(p_caseid)
     AND public.current_user_role() IS DISTINCT FROM 'admin' THEN
    RAISE EXCEPTION 'Only investigators assigned to this case can see its chat'
      USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT * FROM (
    SELECT m.messageid, m.caseid, m.senderid,
           btrim(concat_ws(' ', u.firstname, u.surname)) AS sender_name,
           m.senderid = public.current_user_id() AS is_mine,
           m.body, m.sentat
    FROM public.casemessage m
    JOIN public."User" u ON u.userid = m.senderid
    WHERE m.caseid = p_caseid
      AND (p_after_id IS NULL OR m.messageid > p_after_id)
    ORDER BY m.messageid DESC
    LIMIT LEAST(GREATEST(COALESCE(p_limit, 200), 1), 500)
  ) newest
  ORDER BY newest.messageid;
END;
$$;


-- --- send_case_message: post to the chat
-- The insert policy is what actually decides, this just gives clearer error
-- messages. Returns the message in the same shape as list_case_messages.
CREATE OR REPLACE FUNCTION public.send_case_message(p_caseid integer, p_body text)
  RETURNS TABLE (
    messageid   bigint,
    caseid      integer,
    senderid    integer,
    sender_name text,
    is_mine     boolean,
    body        text,
    sentat      timestamptz
  )
  LANGUAGE plpgsql
  SECURITY INVOKER            -- so the insert policy applies
  SET search_path = ''
AS $$
DECLARE
  v_body   text := btrim(COALESCE(p_body, ''));
  v_status text;
  v_id     bigint;
BEGIN
  IF v_body = '' THEN
    RAISE EXCEPTION 'Type a message first' USING ERRCODE = '22023';
  END IF;
  IF length(v_body) > 2000 THEN
    RAISE EXCEPTION 'Messages can be at most 2000 characters' USING ERRCODE = '22023';
  END IF;
  IF public.current_user_role() IS DISTINCT FROM 'investigator'
     OR NOT public.is_assigned_to_case(p_caseid) THEN
    RAISE EXCEPTION 'Only investigators assigned to this case can post in its chat'
      USING ERRCODE = '42501';
  END IF;
  SELECT c.status INTO v_status FROM public.cases c WHERE c.caseid = p_caseid;
  IF v_status = 'closed' THEN
    RAISE EXCEPTION 'This case is closed: its chat is read-only' USING ERRCODE = '42501';
  END IF;

  INSERT INTO public.casemessage (caseid, body)
  VALUES (p_caseid, v_body)
  RETURNING casemessage.messageid INTO v_id;

  RETURN QUERY
  SELECT l.* FROM public.list_case_messages(p_caseid, v_id - 1, 1) l
  WHERE l.messageid = v_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.list_case_messages(integer, bigint, integer) FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.send_case_message(integer, text)             FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION public.list_case_messages(integer, bigint, integer) TO authenticated, service_role;
GRANT  EXECUTE ON FUNCTION public.send_case_message(integer, text)             TO authenticated, service_role;


-- --- live updates through Realtime. The publication exists on every Supabase
-- project, we skip this anywhere else.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.casemessage;
  END IF;
END $$;
